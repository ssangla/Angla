#!/usr/bin/env bash
set -euo pipefail

# ============================================================
# ANGLA — One-Command Firebase Setup & Deploy
# Run: chmod +x setup.sh && ./setup.sh
# ============================================================

RED='\033[0;31m'
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo -e "${BLUE}"
echo "    _    _   _  ____ _        _    "
echo "   / \  | \ | |/ ___| |      / \   "
echo "  / _ \ |  \| | |  _| |     / _ \  "
echo " / ___ \| |\  | |_| | |___ / ___ \ "
echo "/_/   \_\_| \_|\____|_____/_/   \_\\"
echo ""
echo -e "${NC}AI Couple Finance Copilot — Setup Script"
echo "=========================================="
echo ""

# --- Step 1: Check prerequisites ---
echo -e "${YELLOW}[1/8] Checking prerequisites...${NC}"

command -v node >/dev/null 2>&1 || { echo -e "${RED}Node.js not found. Install from https://nodejs.org${NC}"; exit 1; }
command -v npm >/dev/null 2>&1 || { echo -e "${RED}npm not found.${NC}"; exit 1; }

NODE_VERSION=$(node -v | cut -d'v' -f2 | cut -d'.' -f1)
if [ "$NODE_VERSION" -lt 18 ]; then
  echo -e "${RED}Node.js 18+ required. Current: $(node -v)${NC}"
  exit 1
fi

echo -e "${GREEN}  Node.js $(node -v) ✓${NC}"
echo -e "${GREEN}  npm $(npm -v) ✓${NC}"

# --- Step 2: Install Firebase CLI if needed ---
echo -e "${YELLOW}[2/8] Installing Firebase CLI...${NC}"
if ! command -v firebase >/dev/null 2>&1; then
  npm install -g firebase-tools
fi
echo -e "${GREEN}  Firebase CLI $(firebase --version) ✓${NC}"

# --- Step 3: Firebase Login ---
echo -e "${YELLOW}[3/8] Firebase Authentication...${NC}"
echo -e "  A browser window will open. Sign in with: ${BLUE}simonsangla@gmail.com${NC}"
echo ""
firebase login || { echo -e "${RED}Login failed. Try: firebase login --reauth${NC}"; exit 1; }
echo -e "${GREEN}  Authenticated ✓${NC}"

# --- Step 4: Create Firebase Project ---
echo -e "${YELLOW}[4/8] Creating Firebase project...${NC}"
PROJECT_ID="angla-app-$(date +%s | tail -c 7)"
echo -e "  Project ID: ${BLUE}${PROJECT_ID}${NC}"

firebase projects:create "$PROJECT_ID" --display-name "Angla" 2>/dev/null || {
  echo -e "${YELLOW}  Project may already exist. Trying to use existing...${NC}"
  PROJECT_ID="angla-app"
}

# Update .firebaserc with actual project ID
cat > .firebaserc << EOF
{
  "projects": {
    "default": "${PROJECT_ID}"
  }
}
EOF

firebase use "$PROJECT_ID"
echo -e "${GREEN}  Project ${PROJECT_ID} ready ✓${NC}"

# --- Step 5: Enable Firebase Services ---
echo -e "${YELLOW}[5/8] Enabling Firebase services...${NC}"

# Get web app config
echo "  Creating web app..."
firebase apps:create web "Angla Web" --project "$PROJECT_ID" 2>/dev/null || true

# Get the config
echo "  Fetching Firebase config..."
CONFIG_JSON=$(firebase apps:sdkconfig web --project "$PROJECT_ID" 2>/dev/null | grep -A 20 'firebaseConfig')

# Extract values using node
API_KEY=$(echo "$CONFIG_JSON" | grep apiKey | sed 's/.*"\(.*\)".*/\1/')
AUTH_DOMAIN=$(echo "$CONFIG_JSON" | grep authDomain | sed 's/.*"\(.*\)".*/\1/')
STORAGE_BUCKET=$(echo "$CONFIG_JSON" | grep storageBucket | sed 's/.*"\(.*\)".*/\1/')
MESSAGING_ID=$(echo "$CONFIG_JSON" | grep messagingSenderId | sed 's/.*"\(.*\)".*/\1/')
APP_ID=$(echo "$CONFIG_JSON" | grep appId | sed 's/.*"\(.*\)".*/\1/')

# Write .env file
cat > .env << EOF
# Firebase Configuration (auto-generated by setup.sh)
EXPO_PUBLIC_FIREBASE_API_KEY=${API_KEY}
EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN=${AUTH_DOMAIN}
EXPO_PUBLIC_FIREBASE_PROJECT_ID=${PROJECT_ID}
EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET=${STORAGE_BUCKET}
EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${MESSAGING_ID}
EXPO_PUBLIC_FIREBASE_APP_ID=${APP_ID}
EOF

echo -e "${GREEN}  .env file created with Firebase config ✓${NC}"

# Update packages/firebase-config/src/config.ts with real values
sed -i "s|'YOUR_API_KEY'|'${API_KEY}'|g" packages/firebase-config/src/config.ts 2>/dev/null || true
sed -i "s|'angla-app.firebaseapp.com'|'${AUTH_DOMAIN}'|g" packages/firebase-config/src/config.ts 2>/dev/null || true
sed -i "s|'angla-app'|'${PROJECT_ID}'|g" packages/firebase-config/src/config.ts 2>/dev/null || true

echo -e "${GREEN}  Firebase config injected into source ✓${NC}"

# --- Step 6: Install dependencies ---
echo -e "${YELLOW}[6/8] Installing dependencies...${NC}"
npm install
echo -e "${GREEN}  Dependencies installed ✓${NC}"

# --- Step 7: Deploy Firestore Rules + Hosting ---
echo -e "${YELLOW}[7/8] Deploying to Firebase...${NC}"

echo "  Deploying Firestore rules & indexes..."
firebase deploy --only firestore --project "$PROJECT_ID" 2>&1 || echo -e "${YELLOW}  Firestore deploy skipped (enable Firestore in console first)${NC}"

echo "  Deploying hosting (landing page)..."
firebase deploy --only hosting --project "$PROJECT_ID" 2>&1
echo -e "${GREEN}  Hosting deployed ✓${NC}"

# --- Step 8: Get URLs ---
echo -e "${YELLOW}[8/8] Getting your URLs...${NC}"
HOSTING_URL="https://${PROJECT_ID}.web.app"

echo ""
echo -e "${GREEN}=========================================="
echo -e "  ANGLA IS LIVE!"
echo -e "==========================================${NC}"
echo ""
echo -e "  Landing Page:  ${BLUE}${HOSTING_URL}${NC}"
echo -e "  Firebase Console: ${BLUE}https://console.firebase.google.com/project/${PROJECT_ID}${NC}"
echo ""
echo -e "${YELLOW}  NEXT STEPS:${NC}"
echo -e "  1. Enable Authentication in Firebase Console:"
echo -e "     ${BLUE}https://console.firebase.google.com/project/${PROJECT_ID}/authentication${NC}"
echo -e "     -> Sign-in method -> Enable Email/Password + Google"
echo ""
echo -e "  2. Enable Cloud Firestore:"
echo -e "     ${BLUE}https://console.firebase.google.com/project/${PROJECT_ID}/firestore${NC}"
echo -e "     -> Create database -> Start in production mode"
echo ""
echo -e "  3. Run the mobile app:"
echo -e "     ${BLUE}npm run mobile${NC}"
echo ""
echo -e "  4. Re-deploy Firestore rules after enabling Firestore:"
echo -e "     ${BLUE}firebase deploy --only firestore${NC}"
echo ""
echo -e "${GREEN}  Your email: simonsangla@gmail.com${NC}"
echo -e "${GREEN}  Sent to your inbox? Visit ${HOSTING_URL} to see your live site!${NC}"
echo ""
